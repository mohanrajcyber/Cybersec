export function normalizeCollegeQuery(q) {
  return q
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/\bfor women\b/g, 'women')
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

function tokenOverlap(a, b) {
  const ta = new Set(a.split(' ').filter((w) => w.length > 2))
  const tb = new Set(b.split(' ').filter((w) => w.length > 2))
  if (!ta.size || !tb.size) return 0
  let hit = 0
  ta.forEach((t) => { if (tb.has(t)) hit += 1 })
  return hit / Math.max(ta.size, tb.size)
}

export function matchCollegeByDomain(domain) {
  const d = domain.toLowerCase().replace(/^www\./, '').split('/')[0]
  if (!d) return null
  for (const college of COLLEGE_DIRECTORY) {
    const site = college.website?.replace(/^https?:\/\//, '').replace(/^www\./, '').split('/')[0]
    if (site && d === site) return college
  }
  return null
}

export function matchCollegeDirectory(query) {
  const n = normalizeCollegeQuery(query)
  if (!n) return null

  const locationHints = {
    'auxilium-regunathapuram': ['regunathapuram', 'pudukkottai', 'karambakkudi', '622302', 'auxiliumcollege'],
    'auxilium-aascw-madurai': ['madurai', 'chittampatti', 'aascw', '625122', 'kamaraj'],
  }

  let best = null
  let bestScore = 0

  for (const college of COLLEGE_DIRECTORY) {
    for (const alias of college.names) {
      const a = normalizeCollegeQuery(alias)
      let score = 0
      if (n === a) score = 1
      else if (n.includes(a) || a.includes(n)) score = 0.85
      else score = tokenOverlap(n, a)

      score += (college.priority || 0) / 1000

      const hints = locationHints[college.id] || []
      if (hints.some((h) => n.includes(normalizeCollegeQuery(h)))) score += 0.15

      if (score > bestScore) {
        bestScore = score
        best = college
      }
    }
  }

  return bestScore >= 0.45 ? best : null
}

