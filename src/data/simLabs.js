/** Shared lab detail template */
export function makeLabDetails(title, what, why, how, tools, benefits, ethics) {
  return [
    { id: 'what', icon: '🔍', title: `What is ${title}?`, type: 'concept', content: what },
    { id: 'why', icon: '💡', title: 'Why Learn This?', type: 'why', content: why },
    { id: 'how', icon: '📋', title: 'How to Use This Lab?', type: 'how', content: how },
    { id: 'tools', icon: '🧰', title: 'Tools & Skills', type: 'tools', content: tools },
    { id: 'benefits', icon: '🎯', title: 'Career Uses', type: 'benefits', content: benefits },
    { id: 'ethics', icon: '⚖️', title: 'Ethics & Legal', type: 'ethics', content: ethics || 'Training simulation only. Never test systems without written authorization.' },
  ]
}

function q(id, meta, scenario, question, options, correctId, explain) {
  return {
    id,
    type: 'quiz',
    path: `/lab/${id}`,
    steps: ['Read', 'Analyze', 'Answer'],
    scenario,
    question,
    options,
    correctId,
    explain,
    ...meta,
  }
}

